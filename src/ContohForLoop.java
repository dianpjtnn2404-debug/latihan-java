public class ContohForLoop {
    public static void main(String[] args) {
        for (int k = 1; k <= 10; k++) {
            System.out.println(k);
        }

        int[] nums = {1, 2, 3, 4, 5};
        for (int n : nums) {
            System.out.println(n);
        }
    }
}
